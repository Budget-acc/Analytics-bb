# Redis (session management) — separate logical DB from Celery's broker DB (0)
# so session keys never mix with Celery broker keys on the same Redis instance.
#
# Redis here is an OPTIONAL acceleration layer for session management, never
# a hard dependency for authentication or the database - see
# authentication/session_manager.py. Set REDIS_ENABLED=false (e.g. for local
# development without a Redis server running) to skip attempting Redis
# entirely; the app then runs on the pre-existing password_changed_at-based
# authentication logic. When REDIS_ENABLED is true but Redis is temporarily
# unreachable, the same fallback kicks in automatically (short socket
# timeouts below make that fail fast rather than hang).
REDIS_ENABLED = parse_env_bool("REDIS_ENABLED", True)
REDIS_URL = os.getenv("REDIS_URL", os.getenv("CELERY_BROKER_URL", "redis://localhost:6379/0"))

# Validate SESSION_REDIS_DB is a genuine Redis DB index (0-15) rather than
# deferring the failure to the first cache operation with an opaque error.
# Falls back to the safe default ("1") on a bad value instead of raising -
# a misconfigured env var here must not crash the whole app at startup,
# consistent with Redis being an optional layer everywhere else in this
# feature (see authentication/session_manager.py).
_session_redis_db_raw = os.getenv("SESSION_REDIS_DB", "1")
try:
    _session_redis_db_int = int(_session_redis_db_raw)
    if not (0 <= _session_redis_db_int <= 15):
        raise ValueError(f"must be between 0 and 15, got {_session_redis_db_int}")
    SESSION_REDIS_DB = str(_session_redis_db_int)
except ValueError as _e:
    import logging as _logging
    _logging.getLogger("api_requests").warning(
        f"Invalid SESSION_REDIS_DB={_session_redis_db_raw!r} ({_e}); falling back to '1'."
    )
    SESSION_REDIS_DB = "1"

# Replace the URL's path (DB index) rather than a positional rsplit('/', 1) -
# a URL with no DB-index segment at all (e.g. "redis://localhost:6379", a
# valid Celery-broker-style URL) would make rsplit split on the "//" after
# the scheme instead, producing a broken "redis:/​/1" location.
SESSION_REDIS_LOCATION = urllib.parse.urlunsplit(
    urllib.parse.urlsplit(REDIS_URL)._replace(path=f"/{SESSION_REDIS_DB}")
)

