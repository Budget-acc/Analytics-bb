from collections import defaultdict

from booking_v2.models import (
    PaymentDetailsV2,
    RefundDetails,
    SecurityDepositAdjustment,
    SecurityDepositPayment,
)
from sales.models import SalesPaymentDetails
from tailored.models import (
    CustomerPayment,
    TailorOrderRefund,
    TailorOrderSecurityDepositAdjustment,
    TailorPayment,
)

# transaction_type -> (model whose row `reference_id` currently points at,
# field on that model holding the real parent entity id).
# Types not listed here already store the correct id in `reference_id`
# (e.g. expense, product_expense, manual_income, investment, withdrawal,
# transfer_in/out, tailor_order_security_in) and need no resolution.
JOIN_MAP = {
    "booking_payment": (PaymentDetailsV2, "booking_id"),
    "security_in": (SecurityDepositPayment, "booking_id"),
    "security_out": (SecurityDepositAdjustment, "booking_id"),
    "refund": (RefundDetails, "booking_id"),
    "sale_payment": (SalesPaymentDetails, "sale_id"),
    "tailor_order_payment": (CustomerPayment, "order_id"),
    "tailor_order_refund": (TailorOrderRefund, "order_id"),
    "tailor_security_refund": (TailorOrderSecurityDepositAdjustment, "order_id"),
    "tailor_payment": (TailorPayment, "tailor_id"),
}


def resolve_ledger_reference_ids(entries):
    """
    Mutates each entry's .reference_id in place so it points at the real
    parent business entity (booking/sale/tailor_order/etc.) instead of an
    intermediate payment/adjustment/refund row, per transaction_type.
    Types not in JOIN_MAP are already correct and are left untouched.

    Runs at most one bulk query per distinct transaction_type present in
    `entries` (capped at len(JOIN_MAP)) - never one query per row, so this
    stays O(distinct types) instead of O(n).
    """
    by_type = defaultdict(list)
    for entry in entries:
        if entry.transaction_type in JOIN_MAP:
            by_type[entry.transaction_type].append(entry)

    for txn_type, group in by_type.items():
        # security_out entries auto-generated by migrate_ledger_history.py
        # for completed bookings already carry the real booking id
        # (reference_type == "BookingV2") - skip the join for those.
        if txn_type == "security_out":
            group = [e for e in group if e.reference_type != "BookingV2"]
            if not group:
                continue

        model, join_field = JOIN_MAP[txn_type]
        ids = {e.reference_id for e in group}
        id_map = dict(model.objects.filter(id__in=ids).values_list("id", join_field))

        for entry in group:
            # Fall back to the original reference_id if the joined row is
            # missing (e.g. hard-deleted) rather than erroring/nulling it.
            entry.reference_id = id_map.get(entry.reference_id, entry.reference_id)
