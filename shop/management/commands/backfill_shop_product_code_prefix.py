"""
Management command: backfill_shop_product_code_prefix
========================================================

Purpose
-------
Assigns `ShopNumberingSequence.product_code_prefix` (a shop-unique
5-character prefix for product codes — 2 chars from the shop's `name` + 3
chars from its `place`, e.g. "POKCI") to shops that don't have one yet.
New shops already get a prefix automatically via `Shop.save()` (see
`shop._ensure_product_code_prefix`), so this command exists purely to
backfill shops created before this field/hook existed.

This field has NO Shop-model counterpart to copy from — unlike the other
`ShopNumberingSequence` fields (see `backfill_shop_numbering_sequence`),
there is nothing to migrate; every value here is freshly generated by
`shop.utils.product_code_prefix.generate_unique_product_code_prefix`.

Because a prefix, once set (auto or manually overridden by an admin), must
never be regenerated, this command NEVER overwrites an existing
`product_code_prefix` — it only ever fills in shops that don't have one.
There is no "full regenerate" mode for this field (unlike
`backfill_product_unique_code`), by design.

Usage
-----
# Backfill missing prefixes for ALL shops:
    python manage.py backfill_shop_product_code_prefix

# Preview without writing:
    python manage.py backfill_shop_product_code_prefix --dry-run

# Scope to specific shops (comma-separated IDs):
    python manage.py backfill_shop_product_code_prefix --shop_ids 12,45,78

`--shop_ids` composes with `--dry-run`. There is no `--missing-only` flag —
that's this command's only behavior, since existing prefixes are never
touched.

How it works (bulk, no N+1 queries)
------------------------------------
1. Parses/validates `--shop_ids` (comma-separated ints; every ID must match
   an existing non-deleted Shop, or the command errors out with no writes).
2. Builds ONE Shop queryset (`deleted__isnull=True`, optionally scoped to
   `--shop_ids`), `.only("id", "name", "place")`.
3. Runs ONE query to find which of those shops already have a
   ShopNumberingSequence row with a set `product_code_prefix` — those are
   skipped entirely.
4. Runs ONE more query to load every `product_code_prefix` already in use
   anywhere (not just the candidate shops) into an in-memory set — this is
   the full collision universe, since prefixes must be globally unique.
5. Iterates the (already bounded) candidate shops once in Python, calling
   `generate_unique_product_code_prefix(name, place, taken_prefixes)` for
   each — checking only against the in-memory set, and adding each newly
   assigned prefix to that set before moving to the next shop, so
   collisions within this same run are also resolved correctly. No
   database query happens inside the loop.
6. Writes results with `bulk_create(update_conflicts=True,
   unique_fields=["shop"], update_fields=["product_code_prefix"])` in one
   batched call inside a `transaction.atomic()` block — creating a
   ShopNumberingSequence row for shops that don't have one yet, or setting
   the field on ones that do (but were missing just this field).

Safety / idempotency
---------------------
- Re-running is always safe: shops that already have a `product_code_prefix`
  are found and skipped up front, every time.
- Never modifies an already-set prefix, whether it was auto-generated by an
  earlier run or manually overridden by an admin.
- `--shop_ids` validation happens before any writes; an invalid ID aborts
  the whole run with no partial writes.
- `--dry-run` never writes; it only prints what would happen.
- If, in the extremely unlikely case, no unique prefix can be derived for a
  shop even after all deterministic fallbacks
  (`ProductCodePrefixGenerationError`), that single shop is reported as a
  failure and skipped — it does not abort the rest of the run.

When to run
-----------
- Run once per environment after the `product_code_prefix` field/migration
  is deployed, to backfill all shops created before this feature existed.
- Safe to re-run at any time — a no-op once every shop has a prefix.
"""

from django.core.management.base import BaseCommand
from django.db import transaction
from shop.models import Shop, ShopNumberingSequence
from shop.utils.product_code_prefix import (
    generate_unique_product_code_prefix,
    ProductCodePrefixGenerationError,
)


class Command(BaseCommand):
    help = (
        "Backfill ShopNumberingSequence.product_code_prefix for shops that don't "
        "have one yet. Never overwrites an existing prefix. Use --shop_ids to scope "
        "to specific shops. Safe to re-run."
    )

    def add_arguments(self, parser):
        parser.add_argument(
            "--dry-run",
            action="store_true",
            help="Preview affected shops without writing to the database.",
        )
        parser.add_argument(
            "--shop_ids",
            type=str,
            default=None,
            help="Comma-separated list of shop IDs to scope the backfill to, e.g. 12,45,78.",
        )

    def handle(self, *args, **options):
        dry_run = options["dry_run"]
        shop_ids_raw = options["shop_ids"]

        shop_ids = None
        if shop_ids_raw:
            try:
                shop_ids = [int(part.strip()) for part in shop_ids_raw.split(",") if part.strip()]
            except ValueError:
                self.stderr.write(
                    self.style.ERROR(f"--shop_ids must be a comma-separated list of integers, got: {shop_ids_raw!r}")
                )
                return

            if not shop_ids:
                self.stderr.write(self.style.ERROR("--shop_ids must contain at least one shop ID."))
                return

            found_ids = set(
                Shop.objects.filter(deleted__isnull=True, id__in=shop_ids).values_list("id", flat=True)
            )
            missing_ids = sorted(set(shop_ids) - found_ids)
            if missing_ids:
                self.stderr.write(
                    self.style.ERROR(
                        f"No non-deleted shop found for id(s): {', '.join(str(i) for i in missing_ids)}."
                    )
                )
                return

        qs = Shop.objects.filter(deleted__isnull=True).only("id", "name", "place")
        if shop_ids is not None:
            qs = qs.filter(id__in=shop_ids)

        candidate_shop_ids = list(qs.values_list("id", flat=True))

        already_prefixed_shop_ids = set(
            ShopNumberingSequence.objects.filter(
                shop_id__in=candidate_shop_ids
            ).exclude(product_code_prefix__isnull=True).exclude(
                product_code_prefix=""
            ).values_list("shop_id", flat=True)
        )

        qs = qs.exclude(id__in=already_prefixed_shop_ids).order_by("id")
        total = qs.count()

        scope_label = f", shop_ids={shop_ids}" if shop_ids is not None else ", all shops"
        self.stdout.write(
            f"{'[DRY RUN] ' if dry_run else ''}Backfilling product_code_prefix "
            f"(missing-only{scope_label})..."
        )

        if total == 0:
            self.stdout.write(self.style.SUCCESS("No shops missing a product_code_prefix. Nothing to do."))
            return

        # Global collision universe: every product_code_prefix already in use,
        # anywhere — loaded once, updated in memory as this run assigns more.
        taken_prefixes = set(
            ShopNumberingSequence.objects.exclude(product_code_prefix__isnull=True)
            .exclude(product_code_prefix="")
            .values_list("product_code_prefix", flat=True)
        )

        to_upsert = []
        failures = []
        assignable = 0

        for shop in qs.iterator(chunk_size=2000):
            try:
                prefix = generate_unique_product_code_prefix(shop.name, shop.place, taken_prefixes)
            except ProductCodePrefixGenerationError as exc:
                failures.append((shop.id, str(exc)))
                continue

            taken_prefixes.add(prefix)
            assignable += 1

            if dry_run:
                self.stdout.write(f"  [would assign] shop id={shop.id} name='{shop.name}' -> '{prefix}'")
                continue

            to_upsert.append(ShopNumberingSequence(shop_id=shop.id, product_code_prefix=prefix))

        for shop_id, error in failures:
            self.stderr.write(self.style.ERROR(f"  [failed] shop id={shop_id}: {error}"))

        if dry_run:
            self.stdout.write(
                self.style.SUCCESS(
                    f"[DRY RUN] would assign prefixes to {assignable} shop(s), {len(failures)} failure(s)."
                )
            )
            return

        if to_upsert:
            with transaction.atomic():
                ShopNumberingSequence.objects.bulk_create(
                    to_upsert,
                    batch_size=500,
                    update_conflicts=True,
                    unique_fields=["shop"],
                    update_fields=["product_code_prefix"],
                )

        self.stdout.write(
            self.style.SUCCESS(
                f"Done. {len(to_upsert)} shop(s) assigned a product_code_prefix, "
                f"{len(failures)} failure(s)."
            )
        )
