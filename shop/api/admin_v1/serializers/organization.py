from rest_framework import serializers
from shop.models import Organization, Shop


class OrganizationShopSerializer(serializers.ModelSerializer):
    """Lightweight shop summary nested inside an organization retrieve response."""

    class Meta:
        model = Shop
        fields = ["id", "name", "place", "address", "city", "phone", "phone2", "img", "is_active"]


class OrganizationSerializer(serializers.ModelSerializer):
    """
    Full serializer for create / retrieve / update operations.
    slug and public_token are read-only — auto-generated by the model / view.
    shops is populated only when prefetch_related("shops") is used (retrieve endpoint).
    """
    shop_count = serializers.IntegerField(read_only=True, default=0)
    shops = OrganizationShopSerializer(many=True, read_only=True)

    class Meta:
        model = Organization
        fields = [
            "id",
            "name",
            "slug",
            "public_token",
            "phone",
            "phone2",
            "street",
            "gst_number",
            "place",
            "email",
            "city",
            "state",
            "pincode",
            "image",
            "is_active",
            "public_listing_enabled",
            "show_prices_in_public_listing",
            "created_at",
            "shop_count",
            "shops",
        ]
        read_only_fields = ["id", "slug", "public_token", "image", "created_at", "shop_count", "shops"]


