from drf_spectacular.utils import OpenApiResponse, extend_schema
from rest_framework.decorators import action

from invoice_templates.v3.registry import get_definition
from invoice_templates.v3.services.configuration import ConfigurationError
from invoice_templates.v3.services.sharing import (
    ShareError, display_code, lookup_share, shared_configuration,
)

from ...utils import docs, messages
from ...utils.throttles import ShareLookupRateThrottle


@extend_schema(
    tags=[docs.TAG],
    summary="Look up a share code before importing",
    description=(
        "Returns the name, template and settings behind a share code, without importing anything.\n\n"
        "Purpose: Lets the receiving shop confirm what it is importing and preview the shared look "
        "(pass `configuration` to POST templates/{template_code}/preview/) before importing it as a "
        "new customized invoice.\n\n"
        "Context: The source shop is never revealed. A code is valid for 24 hours after it is "
        "generated (expires_at); an expired code returns its own error (error_code "
        f"\"{messages.SHARE_CODE_EXPIRED_ERROR_CODE}\"). Unknown and revoked codes return the "
        "same generic error. Rate limited to 20 lookups/imports per minute per user.\n\n"
        "Accepted inputs:\n"
        "Path parameters (required):\n"
        "- share_code: the code (case-insensitive, hyphens/spaces ignored).\n\n"
        + docs.AUTH_NOTE
    ),
    parameters=[docs.SHARE_CODE_PATH, docs.SHOP_HEADER],
    responses={
        200: OpenApiResponse(description=(
            f"Success. Exact message: {messages.SHARED_FETCHED}\n\n"
            "Response shape (data):\n"
            "- share_code (string), display_code (string).\n"
            "- invoice_name (string): name of the shared customized invoice (default name on import).\n"
            "- template_code (string), template_name (string), template_version (integer).\n"
            "- configuration (object): the shared settings - colors {background, primary, text, "
            "border, cancelled} and font.\n"
            "- is_own_code (boolean): the code was generated by the active shop (cannot be imported)."
        )),
        400: OpenApiResponse(description=(
            "Validation error. Exact messages:\n"
            + messages.bullet(messages.INVALID_SHARE_CODE, messages.SHARE_CODE_EXPIRED, messages.INVALID_SETTINGS)
            + f"\n\nThe expired response also carries error_code \"{messages.SHARE_CODE_EXPIRED_ERROR_CODE}\"."
        )),
        403: docs.R403,
        429: OpenApiResponse(description=f"Rate limited. Exact message: {messages.SHARE_THROTTLED}"),
        500: docs.R500,
    },
    examples=[docs.envelope_example("Success", messages.SHARED_FETCHED, data={
        "share_code": "K7QM2XRP9HTD", "display_code": "K7QM-2XRP-9HTD", "invoice_name": "Wedding Season",
        "template_code": "classic", "template_name": "Classic", "template_version": 1,
        "configuration": {"colors": {"background": "#FDF5EC", "primary": "#8B1E3F", "text": "#1F1F1F",
                                     "border": "#8B1E3F", "cancelled": "#D32F2F"}, "font": "inter"},
        "is_own_code": False,
    })],
)
@action(
    detail=False, methods=["get"], url_path=r"lookup/(?P<share_code>[A-Za-z0-9 -]+)",
    throttle_classes=[ShareLookupRateThrottle],
)
def lookup(self, request, share_code=None):
    try:
        try:
            share = lookup_share(share_code)
            configuration = shared_configuration(share)
        except ShareError as e:
            return self.share_error_response(e)
        except ConfigurationError as e:
            return self.field_errors_response(messages.INVALID_SETTINGS, e.errors, messages.INVALID_SETTINGS_DEV)

        definition = get_definition(share.template.code)
        return self.success_response(
            data={
                "share_code": share.code,
                "display_code": display_code(share.code),
                "invoice_name": share.invoice_name,
                "template_code": share.template.code,
                "template_name": share.template.name,
                "template_version": definition.version,
                "configuration": configuration,
                "is_own_code": share.source_shop_id == self.shop_id,
            },
            message=messages.SHARED_FETCHED,
        )
    except Exception:
        return self.server_error(f"Invoice share lookup failed for shop {self.shop_id}")
